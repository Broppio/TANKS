#!/usr/bin/env python3
"""Generates WarSteel's ammunition from one table.

Writes: the Java ammo table, shell profiles (data/warsteel/warsteel/shells), each vehicle's
Cannon AmmoType list (data/warsteel/sbw/vehicles), crafting recipes, item models, 32x32
textures, English names, and the gun-sight ladder velocities.

Run from the project root:  python3 tools/gen_ammo.py
Penetration figures are War Thunder's values at 10 m / 0 degrees (mm); DropOff is mm lost per
metre, fitted to its 100/500/1000 m figures. Filler is grams of TNT equivalent. Velocity is the
historical muzzle velocity in m/s (Superb Warfare uses blocks per tick, i.e. m/s / 20).
"""
import json, os, glob
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'src/main/resources')
DATA = os.path.join(RES, 'data/warsteel')
ASSETS = os.path.join(RES, 'assets/warsteel')
JAVA = os.path.join(ROOT, 'src/main/java/rev/warsteel/item/AmmoSpecs.java')

V_KV1, V_KV2, V_SH, V_T26, V_TIGER = 'warsteel:kv-1', 'warsteel:kv-2', 'warsteel:m4a3-sherman', 'warsteel:t-26-1931', 'warsteel:tiger-h1'
TIGERS = [V_TIGER, 'warsteel:tiger-h1-grey', 'warsteel:tiger-h1-sand']

# id, name, gun, calibre, class, pen@10m, dropoff, min pen, filler g, velocity m/s, mass kg,
# vehicles, SBW damage (unique per vehicle; also what infantry/other mods' vehicles take),
# fuze delay m, fuze sensitivity mm, colour scheme, sight ladder index (0 = AP ladder, 1 = HE)
AMMO = [
    # T-26: 45 mm 20-K
    ('45mm_br240', 'BR-240', '45 mm 20-K', 45, 'APHE', 62, 0.020, 38, 29, 760, 1.43, [V_T26], 168, 1.2, 10, 'soviet_ap', 0),
    ('45mm_o240', 'O-240', '45 mm 20-K', 45, 'HE', 6, 0.0, 6, 118, 343, 2.14, [V_T26], 133, 0, 0, 'soviet_he', 1),
    # M4A3 (75) Sherman: 75 mm M3
    ('75mm_m61', 'M61', '75 mm M3', 75, 'APHE', 104, 0.026, 70, 67, 618, 6.79, [V_SH], 364, 1.2, 15, 'us_aphe', 0),
    ('75mm_m72', 'M72', '75 mm M3', 75, 'AP', 91, 0.030, 55, 0, 619, 6.32, [V_SH], 340, 0, 0, 'us_ap', 0),
    ('75mm_m48', 'M48', '75 mm M3', 75, 'HE', 14, 0.0, 14, 680, 463, 6.3, [V_SH], 280, 0, 0, 'us_he', 1),
    # KV-1: 76 mm F-34
    ('76mm_br350a', 'BR-350A', '76 mm F-34', 76, 'APHE', 84, 0.017, 55, 155, 662, 6.3, [V_KV1], 420, 1.2, 15, 'soviet_ap', 0),
    ('76mm_of350', 'OF-350', '76 mm F-34', 76, 'HE', 10, 0.0, 10, 710, 680, 6.2, [V_KV1], 322, 0, 0, 'soviet_he', 1),
    # KV-2: 152 mm M-10T
    ('152mm_br540', 'BR-540', '152 mm M-10T', 152, 'APHE', 110, 0.018, 80, 600, 432, 51.07, [V_KV2], 1540, 1.2, 15, 'soviet_ap', 0),
    ('152mm_of530', 'OF-530', '152 mm M-10T', 152, 'HE', 46, 0.0, 46, 6860, 436, 40.0, [V_KV2], 2800, 0, 0, 'soviet_he', 1),
    # Tiger H1: 88 mm KwK 36
    ('88mm_pzgr39', 'PzGr 39', '8.8 cm KwK 36', 88, 'APHE', 162, 0.022, 110, 109, 773, 10.2, TIGERS, 1120, 1.2, 15, 'german_ap', 0),
    ('88mm_pzgr40', 'PzGr 40', '8.8 cm KwK 36', 88, 'APCR', 171, 0.060, 60, 0, 930, 7.3, TIGERS, 1000, 0, 0, 'german_apcr', 0),
    ('88mm_sprgr', 'Sprgr. L/4.5', '8.8 cm KwK 36', 88, 'HE', 13, 0.0, 13, 698, 820, 9.0, TIGERS, 1400, 0, 0, 'german_he', 1),
]

CLASS_LONG = {'AP': 'AP', 'APHE': 'APHE', 'APCR': 'APCR', 'HE': 'HE'}
STACK = {45: 32, 75: 16, 76: 16, 88: 16, 152: 8}
OUT = {45: 8, 75: 4, 76: 4, 88: 3, 152: 1}


def ricochet(cls):
    if cls == 'HE':
        return {'Enabled': True, 'MinAngle': 80.0, 'AlwaysAngle': 88.0, 'OvermatchRatio': 2.0, 'SpeedRetained': 0.5, 'ScatterDegrees': 6.0}
    if cls == 'APCR':
        return {'Enabled': True, 'MinAngle': 58.0, 'AlwaysAngle': 74.0, 'OvermatchRatio': 2.0, 'SpeedRetained': 0.5, 'ScatterDegrees': 8.0}
    return {'Enabled': True, 'MinAngle': 62.0, 'AlwaysAngle': 80.0, 'OvermatchRatio': 2.0, 'SpeedRetained': 0.55, 'ScatterDegrees': 6.0}


# --------------------------------------------------------------------------------------------- profiles
shell_dir = os.path.join(DATA, 'warsteel/shells')
for f in glob.glob(os.path.join(shell_dir, '*.json')):
    d = json.load(open(f))
    if 'UsedBy' in d:  # generated before; templates without UsedBy (hesh_105, smallcal_127) are kept
        os.remove(f)

for (aid, name, gun, cal, cls, pen, drop, mn, filler, vel, mass, vehicles, dmg, fd, fs, scheme, ladder) in AMMO:
    p = {
        '_comment': f'{gun} {name} ({cls}). Generated by tools/gen_ammo.py. Penetration: War Thunder value at 10 m.',
        'UsedBy': vehicles,
        'Item': 'warsteel:' + aid,
        'Name': 'item.warsteel.' + aid,
        'Class': cls,
        'Calibre': cal,
        'Velocity': round(vel / 20.0, 2),
        'Damage': float(dmg),
        'Mass': mass,
        'Penetration': {'Muzzle': float(pen), 'DropoffPerBlock': drop, 'Minimum': float(mn)},
        'Filler': float(filler),
        'Ricochet': ricochet(cls),
        'DefeatedByArmour': True,
    }
    if cls == 'APHE':
        p['FuzeDelay'] = fd
        p['FuzeSensitivity'] = float(fs)
    json.dump(p, open(os.path.join(shell_dir, aid + '.json'), 'w'), indent=2)

# --------------------------------------------------------------------------------------------- vehicles
def sbw_override(a):
    (aid, name, gun, cal, cls, pen, drop, mn, filler, vel, mass, vehicles, dmg, fd, fs, scheme, ladder) = a
    he = cls == 'HE'
    kg = filler / 1000.0
    o = {
        'Icon': 'superbwarfare:textures/overlay/vehicle/weapon/icons/' + ('he_shell.png' if he else 'ap_shell.png'),
        'Velocity': round(vel / 20.0, 2),
        'Damage': dmg,
        # WarSteel replaces the explosion of its own shells (see HeExplosion); these only matter if
        # another mod intercepts the shell first.
        'ExplosionDamage': round(20 + 60 * kg ** (1 / 3), 1) if filler else 0,
        'ExplosionRadius': round(max(0.6, 1.6 * kg ** (1 / 3)), 2) if filler else 0,
        'Name': 'item.warsteel.' + aid,
    }
    if he:
        o['ShellType'] = 'HE'
    return o


by_vehicle = {}
for a in AMMO:
    for v in a[11]:
        by_vehicle.setdefault(v, []).append(a)

for v, ammo in by_vehicle.items():
    path = os.path.join(DATA, 'sbw/vehicles', v.split(':')[1] + '.json')
    if not os.path.exists(path):
        continue
    d = json.load(open(path))
    cannon = d['Weapons']['Cannon']
    first = sbw_override(ammo[0])
    cannon.update({k: first[k] for k in ('Icon', 'Velocity', 'Damage', 'ExplosionDamage', 'ExplosionRadius', 'Name')})
    cannon.pop('ShellType', None)
    cannon['AmmoType'] = ['warsteel:' + ammo[0][0]] + [{'Ammo': 'warsteel:' + a[0], 'Override': sbw_override(a)} for a in ammo[1:]]
    json.dump(d, open(path, 'w'), indent=2)

# --------------------------------------------------------------------------------------------- sights
for f in glob.glob(os.path.join(ASSETS, 'sights/*.json')):
    d = json.load(open(f))
    v = d['UsedBy'][0]
    ammo = by_vehicle.get(v)
    if not ammo:
        continue
    for i, lad in enumerate(d.get('Ladders', [])):
        pick = [a for a in ammo if a[16] == i]
        if pick:
            lad['Velocity'] = round(pick[0][9] / 20.0, 2)
            lad['Label'] = pick[0][1]
    json.dump(d, open(f, 'w'), indent=2, ensure_ascii=False)

# --------------------------------------------------------------------------------------------- recipes
BODY = {45: ('KGK', ' P '), 75: ('CGC', ' P '), 76: ('CGC', 'CPC'), 88: ('CGC', 'SPS'), 152: ('CTC', 'CPC')}
HEAD = {'AP': ' S ', 'APHE': 'SXS', 'APCR': 'SWS', 'HE': 'IXI'}
KEYS = {
    'K': {'item': 'minecraft:copper_ingot'}, 'C': {'item': 'superbwarfare:copper_plate'},
    'G': {'item': 'minecraft:gunpowder'}, 'P': {'item': 'superbwarfare:primer'},
    'S': {'tag': 'c:ingots/steel'}, 'X': {'item': 'superbwarfare:high_energy_explosives'},
    'W': {'item': 'superbwarfare:tungsten_rod'}, 'I': {'item': 'minecraft:iron_ingot'},
    'T': {'item': 'minecraft:tnt'},
}
rdir = os.path.join(DATA, 'recipe')
for a in AMMO:
    aid, cal, cls = a[0], a[3], a[4]
    pattern = [HEAD[cls], BODY[cal][0], BODY[cal][1]]
    used = sorted({ch for row in pattern for ch in row if ch != ' '})
    r = {'type': 'minecraft:crafting_shaped', 'category': 'misc', 'pattern': pattern,
         'key': {k: KEYS[k] for k in used}, 'result': {'id': 'warsteel:' + aid, 'count': OUT[cal]}}
    json.dump(r, open(os.path.join(rdir, 'ammo_' + aid + '.json'), 'w'), indent=2)

# --------------------------------------------------------------------------------------------- lang
lang_path = os.path.join(ASSETS, 'lang/en_us.json')
lang = json.load(open(lang_path))
for a in AMMO:
    lang['item.warsteel.' + a[0]] = f'{a[2]} {a[1]} ({a[4]})'
lang.update({
    'tooltip.warsteel.ammo.class': 'Type: %s',
    'tooltip.warsteel.ammo.pen': 'Penetration: %s mm at 10 m',
    'tooltip.warsteel.ammo.velocity': 'Muzzle velocity: %s m/s',
    'tooltip.warsteel.ammo.filler': 'Explosive filler: %s g TNT',
    'tooltip.warsteel.ammo.mass': 'Projectile mass: %s kg',
    'tooltip.warsteel.ammo.used_by': 'Fits: %s',
})
json.dump(lang, open(lang_path, 'w'), indent=2, ensure_ascii=False)

# --------------------------------------------------------------------------------------------- models + textures
SCHEMES = {
    # body, tip, band
    'soviet_ap': ((40, 40, 42), (190, 30, 30), None),
    'soviet_he': ((105, 110, 100), (105, 110, 100), (40, 40, 42)),
    'us_aphe': ((35, 35, 38), (35, 35, 38), (225, 225, 225)),
    'us_ap': ((35, 35, 38), (35, 35, 38), None),
    'us_he': ((96, 102, 60), (96, 102, 60), (225, 200, 40)),
    'german_ap': ((30, 30, 32), (200, 200, 200), None),
    'german_apcr': ((30, 30, 32), (230, 230, 235), (230, 230, 235)),
    'german_he': ((180, 160, 70), (180, 160, 70), (40, 40, 42)),
}
WIDTH = {45: 6, 75: 8, 76: 8, 88: 9, 152: 12}
os.makedirs(os.path.join(ASSETS, 'textures/item'), exist_ok=True)
for a in AMMO:
    aid, cal, cls, scheme = a[0], a[3], a[4], a[15]
    w = WIDTH[cal]
    body, tip, band = SCHEMES[scheme]
    im = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    dr = ImageDraw.Draw(im)
    x0 = 16 - w // 2
    x1 = x0 + w - 1
    case_top, case_bot = 17, 30
    proj_top = 2 if cal >= 75 else 6
    brass, brass_d, brass_l = (196, 156, 62), (150, 112, 40), (232, 200, 110)
    # casing
    dr.rectangle([x0, case_top, x1, case_bot], fill=brass)
    dr.line([x0, case_top, x0, case_bot], fill=brass_d)
    dr.line([x1, case_top, x1, case_bot], fill=brass_d)
    dr.line([x0 + 1, case_top, x0 + 1, case_bot], fill=brass_l)
    dr.rectangle([x0 - 1, case_bot - 1, x1 + 1, case_bot], fill=brass_d)
    # projectile with an ogive
    for y in range(proj_top, case_top):
        frac = (y - proj_top) / max(1, case_top - proj_top)
        half = (w / 2) * min(1.0, 0.25 + frac * 1.6)
        cx = 16 - 0.5
        xa, xb = int(round(cx - half + 0.5)), int(round(cx + half - 0.5))
        colour = tip if y < proj_top + 3 else body
        dr.line([xa, y, xb, y], fill=colour)
        if xb > xa:
            dr.point([xa, y], fill=tuple(max(0, c - 25) for c in colour))
    if band:
        by = case_top - 4
        dr.line([x0, by, x1, by], fill=band)
        dr.line([x0, by + 1, x1, by + 1], fill=band)
    if cls == 'APCR':
        dr.line([16, proj_top + 2, 16, case_top - 2], fill=(150, 150, 155))  # visible tungsten core
    im.save(os.path.join(ASSETS, 'textures/item', aid + '.png'))
    json.dump({'parent': 'minecraft:item/generated', 'textures': {'layer0': 'warsteel:item/' + aid}},
              open(os.path.join(ASSETS, 'models/item', aid + '.json'), 'w'), indent=2)

# --------------------------------------------------------------------------------------------- java
lines = []
for (aid, name, gun, cal, cls, pen, drop, mn, filler, vel, mass, vehicles, dmg, fd, fs, scheme, ladder) in AMMO:
    vs = ', '.join('"%s"' % v for v in vehicles)
    lines.append(f'      new AmmoSpec("{aid}", "{name}", "{gun}", {cal}, "{cls}", {float(pen)}, {float(filler)}, {float(vel)}, {float(mass)}, {STACK[cal]}, List.of({vs}))')
java = '''package rev.rev.warsteel.item;

import java.util.List;

/** Generated by tools/gen_ammo.py - edit the table there, not here. */
public final class AmmoSpecs {
   public static final List<AmmoSpec> ALL = List.of(
''' + ',\n'.join(lines) + '''
   );

   private AmmoSpecs() {
   }
}
'''
os.makedirs(os.path.dirname(JAVA), exist_ok=True)
open(JAVA, 'w').write(java)
print('generated', len(AMMO), 'rounds for', len(by_vehicle), 'vehicles')
